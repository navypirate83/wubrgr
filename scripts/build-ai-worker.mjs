/* =====================================================================
   MAKING THE BACKGROUND WORKER'S FILE (public/onnx/ai-worker.js)
   A web worker has to be one plain script file the browser can fetch by itself, but the code it runs
   is written as TypeScript in several files in the app. This script joins them into that one file:
     1. it takes each TypeScript file in a fixed order,
     2. strips the TypeScript-only parts (the types) with Node's own tool for it,
     3. removes the "import" lines (everything is in one file now) and the word "export",
     4. puts the lot in one wrapper so its names can't clash with anything, and writes it out.
   Run it after changing any of these files:   node scripts/build-ai-worker.mjs
   "--check" only says whether the committed file is up to date (the tests use that), and changes nothing.
   Names must be different across the joined files (they all share one space now); the test in
   src/lib/scanner/ai/workerProtocol.test.ts runs the finished file to make sure it works.
   ===================================================================== */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const output = join(root, 'public', 'onnx', 'ai-worker.js');

// The pieces, in the order they must appear (each only uses the ones above it)
const pieces = [
  'src/lib/scanner/core/perspective.ts',
  'src/lib/scanner/core/outlineFinder.ts',
  'src/lib/scanner/core/scannerTypes.ts',
  'src/lib/scanner/core/modelInput.ts',
  'src/lib/scanner/ai/aiRunModel.ts',
  'src/lib/scanner/ai/workerProtocol.ts',
  'src/lib/scanner/ai/aiWorkerMain.ts',
];

// One TypeScript file as plain JavaScript, with no imports and no "export"s
function plain(file) {
  const typed = readFileSync(join(root, file), 'utf8').replaceAll('\r\n', '\n');
  const js = stripTypeScriptTypes(typed, { mode: 'strip' });
  return js
    // import lines (possibly over several lines, but never past a semicolon)
    .replace(/^import\s[^;]*?from\s+['"][^'"]+['"];?[ \t]*\r?$/gm, '')
    // "export function", "export const", ... become plain declarations
    .replace(/^export\s+(?=(?:async\s+)?(?:function|const|let|class)\b)/gm, '')
    // (a leftover "export {" or "export default" would mean this script needs teaching something new)
    // the spaces left where the types were taken out: trailing spaces and runs of blank lines are tidied away
    .replace(/[ \t]+$/gm, '')
    .replace(/(\r?\n){3,}/g, '\n\n')
    .replace(/(\S) {2,}(;|,|\))/g, '$1$2')
    .trim();
}

const parts = pieces.map((file) => `/* ----- from ${file} ----- */\n${plain(file)}`);
for (const part of parts) {
  if (/^\s*(export|import)\s/m.test(part)) throw new Error('A piece still has an import or export in it; teach scripts/build-ai-worker.mjs about it');
}

const text = `/* =====================================================================
   THE AI BACKGROUND WORKER (a web worker for the website's scanner)
   MADE BY scripts/build-ai-worker.mjs: DO NOT EDIT THIS FILE BY HAND. Change the TypeScript files named
   below it and run:  node scripts/build-ai-worker.mjs
   It runs the AI model and finds a card's outline in a photo, away from the page, so the page does not
   stutter (see src/lib/scanner/ai/workerProtocol.ts and aiWorker.web.ts). It is fetched only when the
   scanner first needs the AI. The AI runtime (ort.wasm.min.js, in this folder) is loaded into it when
   the page sets the model up.
   ===================================================================== */
(() => {
'use strict';

${parts.join('\n\n')}
})();
`;

// "--check" only says whether the committed file is up to date; otherwise the file is (re)written
if (process.argv.includes('--check')) {
  const same = existsSync(output) && readFileSync(output, 'utf8').replaceAll('\r\n', '\n') === text;
  console.log(same ? 'public/onnx/ai-worker.js is up to date' : 'public/onnx/ai-worker.js is OUT OF DATE: run node scripts/build-ai-worker.mjs');
  process.exit(same ? 0 : 1);
}
writeFileSync(output, text);
console.log('Wrote ' + output + ' (' + Math.round(text.length / 1024) + ' KB)');
